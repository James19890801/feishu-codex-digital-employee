export function normalizeLocale(value) {
  return String(value || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function translate(locale, key, variables = {}) {
  const language = normalizeLocale(locale);
  const template = catalog[language][key] ?? catalog.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? ''));
}

export function runtimeStatusText(locale, runtime) {
  if (runtime?.available) return translate(locale, 'online');
  if (runtime?.installed) return translate(locale, 'runtimeInstalledOnly');
  return translate(locale, 'notInstalled');
}

export function channelSubmitText(locale, channel) {
  if (channel?.protected) return translate(locale, 'primaryProtected');
  return channel?.enabled ? translate(locale, 'saveConnect') : translate(locale, 'configurationSave');
}

